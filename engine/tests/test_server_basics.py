import re
import subprocess
import sys
import threading

from djengine.settings import load_settings


def test_health_requires_token(client):
    assert client.get("/health").status_code == 401
    assert client.get("/health", headers={"X-Token": "bad"}).status_code == 401
    assert client.get("/health", headers={"X-Token": "t"}).json() == {"ok": True}


def test_settings_roundtrip_persists(client, paths):
    h = {"X-Token": "t"}
    s = client.get("/settings", headers=h).json()
    assert s["default_format"] == "mp3" and s["name_template"] == "{artist} - {title}"
    s["default_format"] = "flac"
    assert client.put("/settings", json=s, headers=h).status_code == 200
    assert load_settings(paths.settings_path).default_format == "flac"


def test_corrupt_settings_fall_back_to_defaults(paths):
    paths.settings_path.write_text("{not json")
    assert load_settings(paths.settings_path).download_concurrency == 3


def test_cli_prints_port_line(tmp_path):
    proc = subprocess.Popen(
        [sys.executable, "-m", "djengine", "--port", "0", "--data-root", str(tmp_path)],
        stdout=subprocess.PIPE,
        stderr=subprocess.DEVNULL,
        text=True,
    )
    lines = []
    t = threading.Thread(target=lambda: lines.append(proc.stdout.readline()), daemon=True)
    t.start()
    t.join(15)
    try:
        assert lines, "no port line within 15 s"
        import json

        import httpx

        info = json.loads(lines[0])
        # must be connectable right away: clients connect as soon as they read the line
        r = httpx.get(f"http://127.0.0.1:{info['port']}/health", headers={"X-Token": info["token"]}, timeout=10)
        assert r.json() == {"ok": True}
    finally:
        proc.kill()
        proc.wait()
    # token is generated by the engine (never passed in argv, where other processes can read it)
    assert re.fullmatch(r'\{"port": \d+, "token": "[A-Za-z0-9_\-]{32,}"\}', lines[0].strip())


def test_cors_preflight_allows_app_renderer(client):
    for origin in ("null", "http://localhost:5173"):
        r = client.options("/health", headers={
            "Origin": origin, "Access-Control-Request-Method": "GET", "Access-Control-Request-Headers": "x-token",
        })
        assert r.status_code == 200 and r.headers["access-control-allow-origin"] == origin


def test_cors_rejects_web_origins(client):
    r = client.options("/health", headers={
        "Origin": "https://evil.example.com", "Access-Control-Request-Method": "GET", "Access-Control-Request-Headers": "x-token",
    })
    assert "access-control-allow-origin" not in r.headers


def test_info_reports_folders(client, paths):
    r = client.get("/info", headers={"X-Token": "t"}).json()
    assert r["logs_dir"] == str(paths.logs_dir) and r["data_dir"] == str(paths.root)


def test_engine_exits_when_parent_dies(tmp_path):
    parent = subprocess.Popen([sys.executable, "-c", "import time; time.sleep(4)"])
    engine = subprocess.Popen(
        [sys.executable, "-m", "djengine", "--port", "0", "--data-root", str(tmp_path), "--parent-pid", str(parent.pid)],
        stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, text=True,
    )
    try:
        assert engine.stdout.readline().startswith('{"port"')  # running while the parent lives
        assert engine.poll() is None
        parent.wait()
        engine.wait(timeout=15)  # raises TimeoutExpired if the engine keeps running as an orphan
    finally:
        engine.kill()
